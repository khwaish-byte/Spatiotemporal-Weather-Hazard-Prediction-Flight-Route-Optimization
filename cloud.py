        red_files = glob.glob(os.path.join(base_dir, "train_red", "*.TIF"))
        # Filename pattern: 'red_patch_XX_YY.TIF' -> extracts 'patch_XX_YY.TIF'
        self.patch_ids = [os.path.basename(f).replace("red_", "") for f in red_files]

