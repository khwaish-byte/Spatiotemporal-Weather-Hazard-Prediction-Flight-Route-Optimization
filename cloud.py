def adaptive_routing(risk_map, start, goal, max_fuel):
    """
    Attempts to find the safest possible route that doesn't exceed max_fuel.
    It tests safety profiles from Ultra-Safe down to Emergency/Desperate.
    """
    # Lambda values: [Ultra-Safe, Cautious, Balanced, Aggressive, Desperate]
    safety_profiles = [100.0, 50.0, 20.0, 5.0, 0.0]

    for penalty in safety_profiles:
        # Calculate path with current safety penalty
        path = risk_astar_pathfind(risk_map, start, goal, risk_weight=penalty)

        # If a path is found AND it's shorter than our max fuel, accept it!
        if path and len(path) <= max_fuel:
            return path, penalty

    # If even the 0.0 penalty path is too long, we must divert!
    return None, "DIVERT"

